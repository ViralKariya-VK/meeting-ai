def build_markdown(meeting_id: int, include_unconfirmed: bool = True) -> str:
    m = db.get_meeting(meeting_id)
    if m is None:
        raise ValueError("Unknown meeting")
    summary = db.one("SELECT text, method FROM summaries WHERE meeting_id=? ORDER BY id DESC", (meeting_id,))
    speakers = [r["label"] for r in db.rows("SELECT label FROM speakers WHERE meeting_id=?", (meeting_id,))]
    status_filter = "('confirmed','suggested','needs_review')" if include_unconfirmed else "('confirmed')"
    decisions = db.rows(f"SELECT * FROM decisions WHERE meeting_id=? AND status IN {status_filter} ORDER BY id", (meeting_id,))
    actions = db.rows(f"SELECT * FROM action_items WHERE meeting_id=? AND status IN {status_filter} ORDER BY id", (meeting_id,))

    def tag(row) -> str:
        return {"confirmed": "", "suggested": " _(unconfirmed)_", "needs_review": " _(needs review)_"}.get(row["status"], "")

    lines = [f"# Minutes of Meeting: {m['title']}", "", f"**Date:** {m['meeting_date']} ({m['timezone']})  ",
             f"**Participants:** {', '.join(speakers) if speakers else 'Not recorded'}", "", "## Summary", "",
             (summary["text"] if summary else "_No summary generated._"), "", "## Decisions", ""]
    lines += [f"- {d['text']}{tag(d)}" for d in decisions] or ["_None recorded._"]
    lines += ["", "## Action Items", "", "| Task | Owner | Due | Status |", "|---|---|---|---|"]
    for a in actions:
        due = a["deadline_date"] or (f"{a['deadline_text']} (unresolved)" if a["deadline_text"] else "-")
        lines.append(f"| {a['task']} | {a['owner'] or 'Unassigned'} | {due} | {a['status'].replace('_', ' ')} |")
    if not actions:
        lines.append("| _None recorded_ | | | |")
    lines += ["", "---", "_Draft generated by Meeting AI. Items marked unconfirmed/needs review have not been verified by a person._"]
    return "\n".join(lines)


def save_draft(meeting_id: int, content_md: str) -> int:
    existing = db.one("SELECT id FROM mom_drafts WHERE meeting_id=? ORDER BY id DESC", (meeting_id,))
    if existing:
        db.execute("UPDATE mom_drafts SET content_md=?, updated_at=datetime('now') WHERE id=?", (content_md, existing["id"]))
        return existing["id"]
    return db.execute("INSERT INTO mom_drafts(meeting_id, content_md) VALUES (?,?)", (meeting_id, content_md))


def latest_draft(meeting_id: int) -> Optional[str]:
    r = db.one("SELECT content_md FROM mom_drafts WHERE meeting_id=? ORDER BY id DESC", (meeting_id,))
    return r["content_md"] if r else None


def to_docx_bytes(content_md: str) -> bytes:
    from docx import Document

    doc = Document()
    table_rows: list[list[str]] = []

    def flush_table():
        nonlocal table_rows
        if table_rows:
            t = doc.add_table(rows=len(table_rows), cols=len(table_rows[0]))
            t.style = "Light Grid Accent 1"
            for i, row in enumerate(table_rows):
                for j, cell in enumerate(row):
                    t.cell(i, j).text = cell
            table_rows = []

    for raw in content_md.splitlines():
        line = raw.rstrip()
        if line.startswith("|"):
            cells = [c.strip().replace("_", "") for c in line.strip("|").split("|")]
            if set("".join(cells)) <= set("-: "):
                continue
            table_rows.append(cells)
            continue
        flush_table()
        if line.startswith("# "):
            doc.add_heading(line[2:], 0)
        elif line.startswith("## "):
            doc.add_heading(line[3:], 1)
        elif line.startswith("- "):
            doc.add_paragraph(line[2:].replace("_", ""), style="List Bullet")
        elif line.strip() in ("", "---"):
            continue
        else:
            doc.add_paragraph(line.replace("**", "").replace("_", ""))
    flush_table()
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
